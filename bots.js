// Bot decision logic: weighted-random-but-valid. Every function here is
// pure - it only ever reads its arguments and GAME_BALANCE, never touches
// room/match state directly - so match.js's resolveBotTurn (which already
// has the live player objects and freshly generated offer pools) is the
// only caller, and this stays trivially fuzz-testable headlessly.

import { GAME_BALANCE } from './balance.js';
import { randomChoice } from './utils.js';
import { RANKS, getNextRank } from './player.js';
import { validatePolitik } from './politics.js';
import { validateSabotaj } from './sabotage.js';
import { validateMedia } from './media.js';
import { validateRaid, validateMarketPurchase } from './politicalOpportunities.js';
import { SPY_CATEGORIES } from './investigation.js';
import { getCharacter } from './characters.js';

const { bots: cfg } = GAME_BALANCE;

function weightedPick(items) {
  const total = items.reduce((sum, item) => sum + item.weight, 0);
  if (total <= 0) return items[0] || null;
  let roll = Math.random() * total;
  for (const item of items) {
    roll -= item.weight;
    if (roll <= 0) return item;
  }
  return items[items.length - 1];
}

// Kabel targets anyone ranked above; a normal Sabotaj only ever targets the
// (necessarily full) seat directly above - same restriction validateSabotaj
// itself enforces, just pre-filtered here so weightedPick never sees an
// invalid target.
function pickSabotajTarget(bot, players, avoid = new Set()) {
  if (bot.hasKabel) {
    const candidates = players.filter((p) => p.id !== bot.id && !avoid.has(p.id) && RANKS.indexOf(p.rank) > RANKS.indexOf(bot.rank));
    const valid = candidates.filter((t) => validateSabotaj(bot, t, players, 0, { isKabel: true }).ok);
    return valid.length ? randomChoice(valid) : null;
  }
  const toRank = getNextRank(bot.rank);
  if (!toRank) return null;
  const candidates = players.filter((p) => p.id !== bot.id && !avoid.has(p.id) && p.rank === toRank);
  const valid = candidates.filter((t) => validateSabotaj(bot, t, players, 0).ok);
  return valid.length ? randomChoice(valid) : null;
}

// Biases toward whichever rival's asset is easiest to profitably hit by
// weighting every (target, asset) pair equally and letting a rival who
// simply owns more assets come up more often - the juiciest targets to
// raid are the ones already sitting on the most.
function pickRaidTarget(bot, players, avoid = new Set()) {
  const options = [];
  players
    .filter((p) => p.id !== bot.id && !avoid.has(p.id) && p.assets.length > 0)
    .forEach((target) => {
      target.assets.forEach((asset) => {
        if (validateRaid(bot, target, asset.id, 0).ok) options.push({ target, asset, weight: 1 });
      });
    });
  return options.length ? weightedPick(options) : null;
}

// Backroom contracts the bot is bound by (see match.js's
// buildBotContractPlan): a bot that must "Sabotaj X" does so when it can, and
// one that means to betray a deal does the forbidden thing when it can.
// Returns null when nothing here applies. Every pick is validated first -
// a rejected action would leave the bot's turn stuck.
function pickContractAction(bot, players, plan) {
  const find = (id) => players.find((p) => p.id === id);
  const sabotajOk = (target) => target && validateSabotaj(bot, target, players, 0, { isKabel: Boolean(bot.hasKabel) }).ok;

  const victim = find(plan.forceSabotajVictimId);
  if (sabotajOk(victim)) return { type: 'sabotaj', targetId: victim.id, extraInfluence: 0 };

  const betrayed = find(plan.betrayTargetId);
  if (sabotajOk(betrayed)) return { type: 'sabotaj', targetId: betrayed.id, extraInfluence: 0 };
  const asset = betrayed && betrayed.assets.find((a) => validateRaid(bot, betrayed, a.id, 0).ok);
  if (asset) return { type: 'raid', targetId: betrayed.id, assetId: asset.id, extraInfluence: 0 };

  if (plan.betrayPolitikRank) {
    const check = validatePolitik(bot, players, 0);
    if (check.ok && check.toRank === plan.betrayPolitikRank) return { type: 'politik', extraInfluence: 0 };
  }
  return null;
}

// Returns exactly one turn action to take, never null - Projek has no
// failure condition beyond needing an offer (always true, PROJECT_CARDS is
// never empty), so it's always in the candidate pool as a guaranteed
// fallback. `offers` is { projekOffers, mediaOffers, marketOffers } -
// generated by the caller via the same generate*Offers() functions the UI
// itself uses, kept out of this module to keep it a pure function of its
// arguments.
export function decideBotAction(bot, players, offers, plan = {}) {
  const w = cfg.actionWeights;
  const avoid = plan.avoidTargetIds || new Set();

  const contractAction = pickContractAction(bot, players, plan);
  if (contractAction) return contractAction;

  const candidates = [
    { type: 'projek', weight: w.projek, build: () => ({ type: 'projek', cardId: randomChoice(offers.projekOffers).id }) },
  ];

  const politikCheck = validatePolitik(bot, players, 0);
  if (politikCheck.ok && politikCheck.toRank !== plan.avoidPolitikRank) {
    candidates.push({ type: 'politik', weight: w.politik, build: () => ({ type: 'politik', extraInfluence: 0 }) });
  }

  const sabotajTarget = pickSabotajTarget(bot, players, avoid);
  if (sabotajTarget) {
    candidates.push({ type: 'sabotaj', weight: w.sabotaj, build: () => ({ type: 'sabotaj', targetId: sabotajTarget.id, extraInfluence: 0 }) });
  }

  const mediaTarget = randomChoice(players.filter((p) => p.id !== bot.id && !avoid.has(p.id))) || null;
  const validMediaCards = offers.mediaOffers.filter((card) => validateMedia(bot, card.id, mediaTarget).ok);
  if (validMediaCards.length) {
    candidates.push({
      type: 'media',
      weight: w.media,
      build: () => {
        const card = randomChoice(validMediaCards);
        return { type: 'media', cardId: card.id, targetId: card.kind === 'target' ? mediaTarget.id : undefined };
      },
    });
  }

  const raidPick = pickRaidTarget(bot, players, avoid);
  if (raidPick) {
    candidates.push({ type: 'raid', weight: w.raid, build: () => ({ type: 'raid', targetId: raidPick.target.id, assetId: raidPick.asset.id, extraInfluence: 0 }) });
  }

  // The Black Market's Scandal hit is the whole risk of using it - a bot
  // won't buy its way straight into the 100% Scandal penalty.
  const marketIsSafe = bot.scandal + GAME_BALANCE.blackMarket.scandalGain < GAME_BALANCE.scandal.penaltyThreshold;
  const affordableMarketTypes = marketIsSafe
    ? offers.marketOffers.filter((type) => validateMarketPurchase(bot, type, offers.marketOffers).ok)
    : [];
  if (affordableMarketTypes.length) {
    candidates.push({ type: 'market', weight: w.market, build: () => ({ type: 'market', assetType: randomChoice(affordableMarketTypes) }) });
  }

  return weightedPick(candidates).build();
}

// null when the roll misses, no rival exists, or the bot has nothing it
// can spare - resolveBotTurn treats null as "don't propose this turn".
// `ctx.force` skips the dice (a bot that has decided to start a special deal).
export function decideDealProposal(bot, players, ctx = {}) {
  if (!ctx.force && Math.random() * 100 >= cfg.actionWeights.dealPropose) return null;

  // `ctx.allowedIds`: the only players the offer may go to (Money Man: Dirty Politics holders).
  const rivals = players.filter((p) => p.id !== bot.id && (!ctx.allowedIds || ctx.allowedIds.includes(p.id)));
  if (!rivals.length) return null;

  const distance = (p) => Math.abs(RANKS.indexOf(p.rank) - RANKS.indexOf(bot.rank));
  const minDistance = Math.min(...rivals.map(distance));
  const target = randomChoice(rivals.filter((p) => distance(p) === minDistance));

  const money = Math.floor((bot.money * cfg.dealOfferPercent) / 100);
  const influence = Math.floor((bot.influence * cfg.dealOfferPercent) / 100);
  if (money <= 0 && influence <= 0) return null;

  // Most offers are plain gifts; some come with strings attached (the host
  // rejects any that turn out not to apply, e.g. no seat contest).
  const roll = Math.random();
  const botNext = getNextRank(bot.rank);
  let condition = { type: 'none' };
  if (roll < 0.3) condition = { type: 'noharm' };
  else if (roll < 0.45 && ctx.voteAhead) condition = { type: 'vote', choice: Math.random() < 0.5 ? 'yes' : 'no' };
  else if (roll < 0.6 && botNext && getNextRank(target.rank) === botNext) condition = { type: 'nopolitik' };

  return { targetId: target.id, money, influence, condition };
}

// ---------- Mode Watak: what a bot does with its character ----------

const chance = (pct) => Math.random() * 100 < pct;

// Specials are free, so a bot takes at most one before its normal action.
// `ctx` is built by match.js from the live host state:
//   characterId, round, ready(abilityId), blocked(target), canFalsify(targetId),
//   copyOptions[], endorsement ({ targetSlot, renewed } | null), campaignCost,
//   revealedIds (Set of character ids already public), trialPendingIds (Set of player ids),
//   deckIds[], categoryClue(targetId) (the character category an Investigative Report showed, or null), hasShield.
// Returns null, { kind: 'deal', special }, or
// { abilityId, payload, follow? } - follow: also publish/expose what was found.
// Every plan is built only from things the host has already said are allowed.
export function decideBotSpecial(bot, players, ctx) {
  const c = cfg.character;
  const rivals = players.filter((p) => p.id !== bot.id);
  if (!rivals.length) return null;
  const any = () => randomChoice(rivals);
  const suspect = () => weightedPick(rivals.map((p) => ({ p, weight: 1 + p.scandal / 10 }))).p;

  switch (ctx.characterId) {
    case 'fixer':
      return ctx.ready('special') && chance(c.dealSpecialChance) ? { kind: 'deal', special: 'fixer' } : null;
    case 'moneyMan':
      return ctx.ready('special') && chance(c.dealSpecialChance) ? { kind: 'deal', special: 'funding' } : null;
    case 'spy':
      return ctx.ready('special') && chance(c.useChance)
        ? { abilityId: 'special', payload: { targetId: suspect().id, category: randomChoice(SPY_CATEGORIES) } }
        : null;
    case 'whistleblower':
      return ctx.ready('special') && chance(c.useChance)
        ? { abilityId: 'special', payload: { targetId: suspect().id }, follow: true }
        : null;
    case 'journalist': {
      if (!ctx.ready('special.report') || !chance(c.useChance)) return null;
      const accusable = rivals.filter((p) => !p.revealedCharacter && !ctx.trialPendingIds.has(p.id));
      // A target whose category a report already showed is the one to accuse: the guess is
      // among that category's few cards instead of the whole deck, so a bot dares much more often.
      const known = accusable.filter((p) => ctx.categoryClue(p.id));
      if (ctx.ready('special.mediaTrial') && chance(known.length ? c.mediaTrialKnownChance : c.mediaTrialChance)) {
        // With one copy of each card, your own card and the ones already revealed cannot be anyone else's.
        const unique = (ctx.deckCopies || 1) <= 1;
        const names = ctx.deckIds.filter((id) => unique ? id !== ctx.characterId && !ctx.revealedIds.has(id) : true);
        const target = known.length ? randomChoice(known) : (accusable.length ? randomChoice(accusable) : null);
        const clue = target ? ctx.categoryClue(target.id) : null;
        const narrowed = clue ? names.filter((id) => getCharacter(id)?.category === clue) : names;
        const pool = narrowed.length ? narrowed : names;
        if (target && pool.length) {
          return { abilityId: 'special.mediaTrial', payload: { targetId: target.id, characterId: randomChoice(pool) } };
        }
      }
      return { abilityId: 'special.report', payload: { targetId: suspect().id }, follow: true };
    }
    case 'bureaucrat': {
      if (!ctx.ready('special') || !chance(c.falsifyChance)) return null;
      const targets = rivals.filter((p) => !ctx.blocked(p) && ctx.canFalsify(p.id));
      return targets.length ? { abilityId: 'special', payload: { targetId: randomChoice(targets).id } } : null;
    }
    case 'lawyer':
      return ctx.ready('special') && !ctx.hasShield && !ctx.blocked(bot) && chance(c.shieldChance)
        ? { abilityId: 'special', payload: { targetId: bot.id } }
        : null;
    case 'ally': {
      if (!ctx.ready('special') || !chance(c.allyChance)) return null;
      const targets = rivals.filter((p) => !ctx.blocked(p));
      return targets.length ? { abilityId: 'special', payload: { targetId: randomChoice(targets).id } } : null;
    }
    case 'populist':
      return ctx.ready('special') && bot.money >= ctx.campaignCost + c.campaignBuffer && chance(c.campaignChance)
        ? { abilityId: 'special', payload: {} }
        : null;
    case 'opportunist':
      return ctx.round >= 2 && ctx.copyOptions.length && ctx.ready('special') && chance(c.copyChance)
        ? { abilityId: 'special', payload: { characterId: randomChoice(ctx.copyOptions) } }
        : null;
    case 'kingmaker': {
      // Bonus Voting Power is passive: nothing for a bot to do.
      if (ctx.endorsement) {
        const endorsed = players.find((p) => p.slot === ctx.endorsement.targetSlot);
        if (!ctx.ready('special.withdrawRenew')) return null;
        if (endorsed && endorsed.scandal >= c.withdrawScandal && chance(50)) return { abilityId: 'special.withdrawRenew', payload: { mode: 'withdraw' } };
        if (!ctx.endorsement.renewed && chance(c.renewChance)) return { abilityId: 'special.withdrawRenew', payload: { mode: 'renew' } };
        return null;
      }
      if (ctx.ready('special.endorsement') && bot.influence >= 300 + c.brokerMinInfluence / 2 && chance(c.endorseChance)) {
        return { abilityId: 'special.endorsement', payload: { targetId: any().id } };
      }
      if (ctx.ready('special.powerBroker') && bot.influence >= c.brokerMinInfluence && chance(c.useChance)) {
        const amount = 250 + 50 * Math.floor(Math.random() * 6); // 250-500
        return { abilityId: 'special.powerBroker', payload: { targetId: any().id, amount } };
      }
      return null;
    }
    default:
      return null;
  }
}

// A clean deal never hurts the recipient, so a bot gets more willing to
// accept as its own Scandal climbs - it has nothing left to protect.
export function decideDealResponse(bot, offer) {
  if (offer.canComply === false) return false; // won't sign what it can't deliver
  const total = (offer.money || 0) + (offer.influence || 0);
  const threshold = cfg.dealAcceptMinValue * (1 - Math.min(bot.scandal, 100) / 200);
  return total >= threshold;
}

// Bots don't negotiate: when a human writes to one in a Backroom chat it just
// answers with a stock line, so the chat never feels dead. This never feeds
// back into any decision (accepting, breaking a contract) - purely flavour.
const BOT_CHAT_REPLIES = {
  pending: ['Hmm... biar saya fikir dulu.', 'Tawaran menarik. Kita lihat nanti.', 'Jangan cakap kuat-kuat, dinding ada telinga.'],
  contract: ['Jangan risau, saya pegang janji.', 'Sabar. Saya tahu apa saya buat.', 'Kita sama-sama untung, bukan?', 'Dah janji, janji lah.'],
};

export function pickBotChatReply(kind = 'contract') {
  return randomChoice(BOT_CHAT_REPLIES[kind] || BOT_CHAT_REPLIES.contract);
}
