// Cache-busting for static hosting (GitHub Pages caches files for 10 minutes).
//
// Hashes every game .js file plus style.css and stamps that version onto:
//   - the stylesheet and entry-script URLs in index.html
//   - an import map that points each "./module.js" at "./module.js?v=<hash>"
// A cached old index.html therefore keeps loading one complete old set of
// files, and a fresh index.html loads one complete new set - never a mix.
//
//   node release.mjs          rewrite index.html when the version changed
//   node release.mjs --check  exit 1 if index.html is out of date (no write)
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import url from 'node:url';

const ROOT = path.dirname(url.fileURLToPath(import.meta.url));
const INDEX = path.join(ROOT, 'index.html');

const modules = fs.readdirSync(ROOT).filter((f) => f.endsWith('.js')).sort();
const hash = crypto.createHash('sha1');
[...modules, 'style.css'].forEach((file) => {
  hash.update(file);
  hash.update(fs.readFileSync(path.join(ROOT, file)));
});
const version = hash.digest('hex').slice(0, 8);

const imports = Object.fromEntries(modules.map((f) => [`./${f}`, `./${f}?v=${version}`]));
const importMap = `<!-- importmap:start (generated by release.mjs) -->
<script type="importmap">
${JSON.stringify({ imports }, null, 2)}
</script>
<!-- importmap:end -->`;

const before = fs.readFileSync(INDEX, 'utf8');
let after = before
  .replace(/<!-- importmap:start[\s\S]*?<!-- importmap:end -->/, importMap)
  .replace(/href="style\.css(\?v=\w+)?"/, `href="style.css?v=${version}"`)
  .replace(/src="game\.js(\?v=\w+)?"/, `src="game.js?v=${version}"`);

if (after === before && !before.includes('importmap:start')) {
  // First run: place the import map right after the stylesheet link.
  after = before.replace(
    /(<link rel="stylesheet" href="style\.css[^>]*>)/,
    `$1\n${importMap}`,
  );
  after = after
    .replace(/href="style\.css(\?v=\w+)?"/, `href="style.css?v=${version}"`)
    .replace(/src="game\.js(\?v=\w+)?"/, `src="game.js?v=${version}"`);
}

if (process.argv.includes('--check')) {
  if (after !== before) {
    console.error('index.html is out of date - run: node release.mjs');
    process.exit(1);
  }
} else if (after !== before) {
  fs.writeFileSync(INDEX, after);
  console.log(`index.html stamped with version ${version}`);
} else {
  console.log(`index.html already at version ${version}`);
}
